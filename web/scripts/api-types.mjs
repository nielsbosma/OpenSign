// Generates src/lib/api-types.gen.ts from the Rust services: `cargo run --bin opensign -- schema`.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url));
const out = fileURLToPath(new URL('../src/lib/api-types.gen.ts', import.meta.url));
const json = execFileSync('cargo', ['run', '-q', '--bin', 'opensign', '--', 'schema'], { cwd: root, maxBuffer: 64 * 1024 * 1024 });
const services = JSON.parse(json.toString());

const defs = new Map();

function pascal(name) {
  return name
    .split(/[._]/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');
}

function register(name, schema, renames) {
  const key = JSON.stringify(schema);
  let candidate = name;
  for (let n = 2; defs.has(candidate) && defs.get(candidate).key !== key; n++) candidate = `${name}${n}`;
  if (!defs.has(candidate)) defs.set(candidate, { key, schema, renames });
  return candidate;
}

function quote(name) {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

function doc(schema, indent) {
  const text = schema?.description;
  if (!text) return '';
  return `${indent}/** ${text.replaceAll('*/', '*\\/').replaceAll('\n', ' ')} */\n`;
}

function ts(schema, renames, indent = '') {
  if (schema === true || schema === undefined) return 'unknown';
  if (schema === false) return 'never';
  if (schema.$ref) {
    const name = schema.$ref.replace('#/$defs/', '');
    return renames[name] ?? name;
  }
  if ('const' in schema) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  const union = schema.oneOf ?? schema.anyOf;
  if (union) {
    const base = { ...schema };
    delete base.oneOf;
    delete base.anyOf;
    delete base.description;
    const hasBase = base.properties || base.type;
    return union
      .map((s) => {
        const t = ts(s, renames, indent);
        return hasBase && base.properties ? `(${ts(base, renames, indent)} & ${t})` : t;
      })
      .join(' | ');
  }
  if (schema.allOf) return schema.allOf.map((s) => ts(s, renames, indent)).join(' & ');
  const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
  if (types.length > 1) return types.map((t) => ts({ ...schema, type: t }, renames, indent)).join(' | ');
  switch (types[0]) {
    case 'null':
      return 'null';
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'array':
      if (schema.prefixItems) return `[${schema.prefixItems.map((s) => ts(s, renames, indent)).join(', ')}]`;
      return `Array<${ts(schema.items, renames, indent)}>`;
    case 'object': {
      const props = schema.properties ?? {};
      const required = new Set(schema.required ?? []);
      const inner = `${indent}  `;
      const lines = Object.entries(props).map(
        ([k, v]) => `${doc(v, inner)}${inner}${quote(k)}${required.has(k) ? '' : '?'}: ${ts(v, renames, inner)};`,
      );
      if (schema.additionalProperties && schema.additionalProperties !== false) {
        lines.push(`${inner}[key: string]: ${ts(schema.additionalProperties, renames, inner)};`);
      }
      if (!lines.length) return schema.additionalProperties === false ? 'Record<string, never>' : 'Record<string, unknown>';
      return `{\n${lines.join('\n')}\n${indent}}`;
    }
    default:
      return 'unknown';
  }
}

const entries = [];
for (const [name, service] of Object.entries(services).sort(([a], [b]) => a.localeCompare(b))) {
  const types = {};
  for (const side of ['input', 'output']) {
    const schema = service[side];
    const renames = {};
    for (const def of Object.keys(schema.$defs ?? {})) renames[def] = def;
    for (const [def, body] of Object.entries(schema.$defs ?? {})) renames[def] = register(def, body, renames);
    const top = { ...schema };
    delete top.$defs;
    delete top.$schema;
    delete top.title;
    const typeName = `${pascal(name)}${side === 'input' ? 'Input' : 'Output'}`;
    const shared = schema.title && schema.type === 'object' && schema.properties && !/Input$/.test(schema.title);
    defs.set(typeName, { key: typeName, schema: shared ? { $ref: `#/$defs/${schema.title}` } : top, renames });
    if (shared) renames[schema.title] = register(schema.title, top, renames);
    types[side] = typeName;
  }
  entries.push(`  ${JSON.stringify(name)}: { kind: ${JSON.stringify(service.kind)}; input: ${types.input}; output: ${types.output} };`);
}

const body = [...defs.entries()]
  .map(([name, { schema, renames }]) => `${doc(schema, '')}export type ${name} = ${ts(schema, renames)};`)
  .join('\n\n');
writeFileSync(
  out,
  `// Generated by scripts/api-types.mjs from the Rust services. Do not edit; run \`pnpm api:types\`.\n\n${body}\n\nexport interface Services {\n${entries.join('\n')}\n}\n`,
);
console.log(`Wrote ${Object.keys(services).length} services to ${out}`);
